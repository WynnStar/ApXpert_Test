CREATE TABLE holding_trades (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    holding_id BIGINT NOT NULL,
    side VARCHAR(4) NOT NULL,
    trade_date DATE NOT NULL,
    shares BIGINT NOT NULL,
    unit_price DECIMAL(38, 2) NOT NULL,
    CONSTRAINT fk_holding_trades_holding FOREIGN KEY (holding_id) REFERENCES holdings(id),
    CONSTRAINT ck_holding_trades_side CHECK (side IN ('BUY', 'SELL')),
    CONSTRAINT ck_holding_trades_shares CHECK (shares > 0),
    CONSTRAINT ck_holding_trades_price CHECK (unit_price > 0)
);

CREATE INDEX idx_holding_trades_sequence ON holding_trades (holding_id, trade_date, id);
